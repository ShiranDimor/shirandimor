// חילוץ טלפון/מייל מתוך טקסט חופשי - לזיהוי הזדמנותי כשמישהו משתף פרטי קשר תוך כדי שיחה,
// בלי לבקש את זה בכפייה בתחילת השיחה. תבנית הטלפון מכסה מספרים ישראליים בפורמט מקומי (05...)
// או בינלאומי (972...), עם או בלי מקפים/רווחים.
export function extractContactFromText(text: string): { phone: string | null; email: string | null } {
  const phoneMatch = text.match(/(?:\+?972[-\s]?|0)5\d(?:[-\s]?\d){7}/);
  const emailMatch = text.match(/[\w.+-]+@[\w-]+\.[\w.-]+/);
  return {
    phone: phoneMatch ? phoneMatch[0].replace(/[-\s]/g, '') : null,
    email: emailMatch ? emailMatch[0].toLowerCase() : null,
  };
}

// הקשר זמן-ריצה (runtime context) - מי בדיוק מדבר עם הבוט עכשיו, אם ידוע. זה לא חלק מהפרומפט
// הקבוע (SUPPORT_BOT_SYSTEM_PROMPT), אלא נבנה מחדש בכל קריאה ומצורף אליו - כדי שעדכון הזיהוי
// (לדוגמה: זיהינו שזו מנויה פעילה) לא ידרוש לגעת בטון/בידע הקבועים של הבוט.
export function buildRuntimeContextBlock(ctx: {
  userType: string | null;
  contactName?: string | null;
  nextLive?: { title: string; scheduledAt: string } | null;
  monthStats?: { closedCount: number; winCount: number; monthLabel: string } | null;
}): string {
  const lines: string[] = [];
  switch (ctx.userType) {
    case 'admin_test':
      lines.push('הקשר זמן-ריצה: זו שירן עצמה (אדמין), מדמה שיחה כדי לבדוק ולדייק אותך. אל תציע לה להצטרף למנוי.');
      break;
    case 'member_active':
      lines.push('הקשר זמן-ריצה: זו/זהו כבר מנוי/ה פעיל/ה ב"מדברים עסקאות". אסור להציע לה/לו את המנוי הקיים - להתמקד בשירות, תמיכה, הכוונה לתוכן ותשובות מקצועיות.');
      break;
    case 'updates_group':
      lines.push('הקשר זמן-ריצה: זו/זה כבר נמצא/ת בקבוצת העדכונים החינמית. אפשר להיות מעט יותר ישירים, ולהסביר את ההבדל מ"מדברים עסקאות" דרך עומק התהליך - לא דרך הקטנת הערך של הקבוצה החינמית.');
      break;
    case 'lead_new':
      lines.push('הקשר זמן-ריצה: זהו ליד חדש - לא נמצא/ת באף אחת מהקבוצות של שירן. לתת ערך לפני כל הצעה, לא לפתוח ישר במכירה.');
      break;
    default:
      lines.push('הקשר זמן-ריצה: זהות המשתמש/ת עדיין לא ידועה. אין צורך לשאול על כך ישירות - אם וכאשר ישותפו פרטי קשר תוך כדי שיחה, הזיהוי יתעדכן אוטומטית.');
  }
  if (ctx.contactName) lines.push(`שם שכבר שותף: ${ctx.contactName}.`);

  if (ctx.nextLive) {
    const d = new Date(ctx.nextLive.scheduledAt);
    // חייבים לציין את אזור הזמן של ישראל במפורש - השרת רץ ב-UTC, ובלי זה השעה יוצאת שגויה
    const formatted = d.toLocaleString('he-IL', { day: 'numeric', month: 'numeric', hour: '2-digit', minute: '2-digit', timeZone: 'Asia/Jerusalem' });
    lines.push(`הלייב הקרוב בפועל: "${ctx.nextLive.title}" בתאריך ${formatted}. זה נתון אמיתי ועדכני - אפשר לצטט אותו במדויק.`);
  } else if (ctx.nextLive === null) {
    lines.push('אין כרגע לייב עתידי מפורסם באתר - אם נשאלת מתי הלייב הבא, תגידי בכנות שאין כרגע תאריך קבוע ושהעדכון יבוא בקבוצה.');
  }

  if (ctx.monthStats && ctx.monthStats.closedCount > 0) {
    const winRate = Math.round((ctx.monthStats.winCount / ctx.monthStats.closedCount) * 100);
    lines.push(`נתון אמיתי ומאומת מהתיק החודש (${ctx.monthStats.monthLabel}): ${ctx.monthStats.closedCount} עסקאות נסגרו, ${winRate}% מהן רווחיות. אם משתפים את זה - רק באחוזים כמו כאן, לעולם לא בסכומי כסף, ובטון מאופק (לא "מפוצץ" או מרשים מדי) - בלי להוסיף עליו ובלי להבטיח שהעתיד יחזור על עצמו.`);
  }

  return lines.join(' ');
}

export async function callSupportBot(
  messages: { role: 'user' | 'assistant'; content: string }[],
  runtimeContext?: string
): Promise<string> {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    throw new Error('ANTHROPIC_API_KEY לא מוגדר');
  }

  const model = process.env.ANTHROPIC_MODEL || 'claude-sonnet-4-5-20250929';
  const system = runtimeContext ? `${SUPPORT_BOT_SYSTEM_PROMPT}\n\n${runtimeContext}` : SUPPORT_BOT_SYSTEM_PROMPT;

  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': apiKey,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model,
      max_tokens: 1024,
      system,
      messages,
    }),
  });

  if (!res.ok) {
    const text = await res.text().catch(() => '');
    throw new Error(`שגיאה מ-Anthropic API (${res.status}): ${text}`);
  }

  const data = await res.json();
  const textBlock = data?.content?.find((b: { type: string }) => b.type === 'text');
  return textBlock?.text || '';
}

const SUMMARY_SYSTEM_PROMPT = `אתה מסכם שיחות בין "דור" (העוזרת הדיגיטלית של שירן דימור) לבין מי שכתב לה. תפקידך לכתוב לשירן עצמה סיכום קצר וממוקד בעברית - 2-4 משפטים - על מה שהאדם רצה, מה נענה לו, ואם יש משהו שדורש ממנה מעקב אישי (למשל: כוונת הצטרפות, בקשה לחזרה, שאלה שלא נענתה טוב, תלונה). אל תחזור על כל השיחה מילה במילה - רק תמצית שימושית. אם השיחה הייתה סתם שאלה טכנית שנענתה במלואה בלי המשך נדרש, תגיד את זה בקצרה.`;

// מסכם שיחה שלמה למייל התראה לשירן - שימוש מודל קל וזול, לא אותו קול/פרומפט של דור עצמה
export async function summarizeConversation(messages: { role: 'user' | 'assistant'; content: string }[]): Promise<string> {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) return 'אין סיכום זמין (המפתח לא מוגדר).';

  const model = process.env.ANTHROPIC_SUMMARY_MODEL || process.env.ANTHROPIC_MODEL || 'claude-sonnet-4-5-20250929';

  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': apiKey,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model,
      max_tokens: 300,
      system: SUMMARY_SYSTEM_PROMPT,
      messages: [{ role: 'user', content: `סכמי את השיחה הבאה:\n\n${messages.map((m) => `${m.role === 'user' ? 'המשתמש/ת' : 'דור'}: ${m.content}`).join('\n')}` }],
    }),
  });

  if (!res.ok) return 'שגיאה ביצירת סיכום.';

  const data = await res.json();
  const textBlock = data?.content?.find((b: { type: string }) => b.type === 'text');
  return textBlock?.text || 'לא הופק סיכום.';
}
