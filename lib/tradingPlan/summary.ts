// טקסט מותאם אישית בסיום התוכנית, לפי היעד המרכזי שנבחר.
// לא "אבחון פסיכולוגי" ולא ציונים - רק חידוד עדין של איפה כדאי להתמקד.

export function personalizedNote(mainGoal: string | null | undefined): string | null {
  switch (mainGoal) {
    case 'trade_management':
      return 'נראה שאחד המקומות המרכזיים שכדאי לעבוד עליהם בחודש הקרוב הוא מה שקורה אחרי הכניסה. כניסה טובה היא רק ההתחלה.';
    case 'mentality':
      return 'נראה שהאתגר שלך הוא פחות לדעת מה לעשות ויותר להצליח לבצע את זה בזמן אמת. זה אחד האתגרים הכי נפוצים במסחר.';
    case 'build_strategy':
    case 'better_setups':
      return 'לפני שעובדים על עוד אינדיקטורים, כדאי קודם להגדיר בצורה ברורה איזה Setup אנחנו בכלל מחפשים.';
    case 'discipline':
      return 'לדעת מה נכון לעשות זה החלק הקל. החלק שדורש עבודה הוא לעמוד בזה גם כשהעסקה כבר פתוחה.';
    case 'risk_management':
      return 'ניהול סיכון הוא לא הפרט הכי מרגש במסחר, אבל הוא כמעט תמיד ההבדל בין מי שנשאר בתמונה לטווח ארוך לבין מי שלא.';
    case 'consistency':
      return 'עקביות בדרך כלל לא נבנית מעוד אינדיקטור אחד, אלא מתהליך קבוע שחוזרים עליו גם כשלא מתחשק.';
    default:
      return null;
  }
}
