export function personalizedNote(mainGoals: string[] | null | undefined): string | null {
  if (!mainGoals || !mainGoals.length) return null;

  const notes: Record<string, string> = {
    trade_management: 'נראה שאחד המקומות המרכזיים שכדאי לעבוד עליהם בחודש הקרוב הוא מה שקורה אחרי הכניסה. כניסה טובה היא רק ההתחלה.',
    mentality: 'נראה שהאתגר הוא פחות לדעת מה לעשות ויותר להצליח לבצע את זה בזמן אמת. זה אחד האתגרים הכי נפוצים במסחר.',
    build_strategy: 'לפני שעובדים על עוד אינדיקטורים, כדאי קודם להגדיר בצורה ברורה איזה Setup בכלל מחפשים.',
    better_setups: 'לפני שעובדים על עוד אינדיקטורים, כדאי קודם להגדיר בצורה ברורה איזה Setup בכלל מחפשים.',
    discipline: 'לדעת מה נכון לעשות זה החלק הקל. החלק שדורש עבודה הוא לעמוד בזה גם כשהעסקה כבר פתוחה.',
    risk_management: 'ניהול סיכון הוא לא הפרט הכי מרגש במסחר, אבל הוא כמעט תמיד ההבדל בין מי שנשאר בתמונה לטווח ארוך לבין מי שלא.',
    consistency: 'עקביות בדרך כלל לא נבנית מעוד אינדיקטור אחד, אלא מתהליך קבוע שחוזרים עליו גם כשלא מתחשק.',
  };

  for (const goal of mainGoals) {
    if (notes[goal]) return notes[goal];
  }
  return null;
}
